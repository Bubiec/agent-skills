#!/usr/bin/env python3
"""Export small, metadata-free README images from the owner's video asset pack.

No image generation, cropping or retouching. Original files stay untouched.
The public manifest records filenames and hashes, never local absolute paths.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path, required=True,
                        help="Video pack's 01_sources directory")
    parser.add_argument("--portfolio", type=Path, required=True,
                        help="Existing on-model portfolio image (separate photo series)")
    args = parser.parse_args()
    specs = []
    for product in ("mentor", "eclipse"):
        for number in range(1, 6):
            specs.append((args.sources / "product_reference" / f"{product}-{number}.jpg",
                          f"{product}/input-{number:02d}.jpg", "phone-input", product))
        specs.append((args.sources / "generated_result" / f"{product}-gemini-output.jpg",
                      f"{product}/packshot.jpg", "generated-packshot", product))
        specs.append((args.sources / "generated_result" / f"{product}-set.png",
                      f"{product}/set.jpg", "separate-step-set-result", product))
    specs.extend([
        (args.sources / "generated_result" / "21x9-set-bottom-image.png",
         "accessories.jpg", "existing-accessory-visual", "shared"),
        (args.portfolio, "mentor/on-model.jpg", "earlier-series-portfolio", "mentor"),
    ])
    for source, *_ in specs:
        if not source.is_file():
            raise SystemExit(f"Missing source: {source}")
    destination = ROOT / "docs" / "gallery"
    records = []
    for source, name, role, product in specs:
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(source) as original:
            source_size = list(original.size)
            image = ImageOps.exif_transpose(original).convert("RGB")
            image.thumbnail((960, 960), Image.Resampling.LANCZOS)
            # A new pixel-only image prevents EXIF, GPS and embedded comments leaking.
            clean = Image.new("RGB", image.size)
            clean.paste(image)
            clean.save(target, quality=88, optimize=True, progressive=True)
        records.append({
            "file": name, "role": role, "product": product,
            "source_file": source.name, "source_sha256": digest(source),
            "source_size": source_size, "size": list(clean.size),
            "sha256": digest(target),
        })
    manifest = {
        "collection": "StoreKite product-photo video examples, October 2026",
        "transform": "EXIF orientation, proportional resize to max 960px, JPEG quality 88, metadata removed; no crop or retouch",
        "provenance": "Existing Fotogen workflow assets; not generated by running the public example job.toml. Set images are a separate step using product and accessory visuals. The on-model image belongs to an earlier series, not these phone inputs.",
        "images": records,
    }
    (destination / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Exported {len(records)} images to {destination}")


if __name__ == "__main__":
    main()
